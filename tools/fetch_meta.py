#!/usr/bin/env python3
"""Fetch current-patch hero win rates and bake them into bots/FunLib/meta_weights.lua
for gentle BP biasing (see Customize.SmartPlay.Meta_BP).

Sources:
  * default: OpenDota public API (no auth, 2 calls total):
      /api/constants/heroes  (hero id -> shortname)
      /api/heroStats         (per-bracket pub pick/win)
    Archon (~3000 MMR) is bracket-weighted as b4*0.65 + b5*0.35.
  * --stratz: use the STRATZ GraphQL API instead (token from
    tools/stratz_token.local). Kept to <= 3 calls: one constants query +
    one heroStats query. Respect their rate limits - only run occasionally.

Usage: python tools/fetch_meta.py [--stratz] [--brackets b4=0.65,b5=0.35]
"""

import json
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT_LUA = os.path.join(ROOT, "bots", "FunLib", "meta_weights.lua")

OPENDOTA = "https://api.opendota.com/api"
STRATZ = "https://api.stratz.com/graphql"

# OpenDota bracket buckets -> weight for a ~3000 MMR (Archon) profile
DEFAULT_BRACKET_WEIGHTS = {"4": 0.65, "5": 0.35}


def http_json(url, data=None, headers=None):
    h = {"User-Agent": "Mozilla/5.0 OpenHyperAI-bot-dev"}
    h.update(headers or {})
    req = urllib.request.Request(url, data=data, headers=h)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode("utf-8"))


def fetch_opendota(weights):
    # heroStats rows already embed id/name + per-bracket pick/win: one call
    stats = http_json(OPENDOTA + "/heroStats")
    rows = []
    for h in stats:
        hid = h.get("id")
        name = h.get("name") or ""
        if hid is None or not name.startswith("npc_dota_hero_"):
            continue
        picks = wins = 0.0
        for b, w in weights.items():
            picks += w * float(h.get(f"{b}_pick") or 0)
            wins += w * float(h.get(f"{b}_win") or 0)
        if picks <= 0:
            continue
        rows.append((name.replace("npc_dota_hero_", ""), picks, wins / picks))
    return rows


STRATZ_META_QUERY = """
query { constants { heroes { id shortName } } }
"""

STRATZ_WIN_QUERY = """
query {
  heroStats {
    winWeek(heroVsHeroHeroIds: [], bracketIds: [ARCHON, LEGEND]) {
      heroId
      winCount
      matchCount
      bracketIds
    }
  }
}
"""


def fetch_stratz(token):
    headers = {
        "Authorization": "Bearer " + token,
        "User-Agent": "STRATZ_API",
        "Content-Type": "application/json",
    }
    body = json.dumps({"query": STRATZ_WIN_QUERY}).encode("utf-8")
    data = http_json(STRATZ, data=body, headers=headers)
    if data.get("errors"):
        raise RuntimeError("stratz errors: " + json.dumps(data["errors"])[:300])
    rows_block = data["data"]["heroStats"]["winWeek"]
    heroes = {}
    # aggregated across requested brackets: sum wins / sum matches
    agg = {}
    for row in rows_block:
        short = None
        agg.setdefault(row["heroId"], [0, 0])
        agg[row["heroId"]][0] += row["matchCount"]
        agg[row["heroId"]][1] += row["winCount"]
    const_body = json.dumps({"query": STRATZ_META_QUERY}).encode("utf-8")
    cdata = http_json(STRATZ, data=const_body, headers=headers)
    for h in cdata["data"]["constants"]["heroes"]:
        heroes[h["id"]] = h["shortName"]
    rows = []
    for hid, (m, w) in agg.items():
        if hid in heroes and m > 0:
            rows.append((heroes[hid], m, w / m))
    return rows


def write_lua(rows, source):
    rows.sort(key=lambda r: -r[1])
    lines = [
        "-- meta_weights.lua - GENERATED by tools/fetch_meta.py, do not edit by hand.",
        f"-- source: {source}; re-run the tool after notable balance patches.",
        "-- Used by hero_selection.lua for gentle (+/-10%) pick-score biasing",
        "-- when Customize.SmartPlay.Meta_BP is enabled.",
        "local meta = {}",
        'meta.source = "%s"' % source,
        'meta.updated = "%s"' % __import__("datetime").date.today().isoformat(),
        "meta.winrate = {",
    ]
    for short, picks, wr in rows:
        lines.append('    %s = %.4f,  -- pickshare %.1f%%' % (short, wr, picks))
    lines.append("}")
    lines.append("return meta")
    with open(OUT_LUA, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"[meta] wrote {len(rows)} heroes -> {OUT_LUA}")


def main():
    weights = dict(DEFAULT_BRACKET_WEIGHTS)
    if "--brackets" in sys.argv:
        arg = sys.argv[sys.argv.index("--brackets") + 1]
        weights = dict(kv.split("=") for kv in arg.split(","))
        weights = {k: float(v) for k, v in weights.items()}

    if "--stratz" in sys.argv:
        token_path = os.path.join(HERE, "stratz_token.local")
        if not os.path.exists(token_path):
            print("[meta] tools/stratz_token.local missing; falling back to OpenDota")
        else:
            token = open(token_path, encoding="utf-8").read().strip()
            try:
                rows = fetch_stratz(token)
                write_lua(rows, "stratz")
                return 0
            except Exception as e:  # noqa
                print(f"[meta] STRATZ failed ({e}); falling back to OpenDota")

    rows = fetch_opendota(weights)
    write_lua(rows, "opendota")
    return 0


if __name__ == "__main__":
    sys.exit(main())
